    self.botones = botones
    self.resolucion_pantalla = resolucion_pantalla
    self.procesador = procesador 
    self.memoria_ram = memoria_ram 
    self.camara = camara 
    self.tipo_area_carga = tipo_area_carga 
    self.marca = marca
    self.almacenamiento = almacenamiento 
    self.bateria = bateria 
    self.sistema_operativo = sistema_operativo
   
    print("Funciones de los botones: {self.botones}")
    print("Resolución de la pantalla: {self.resolucion_pantalla}")
    print("Procesador del teléfono: {self.procesador}")
    print("Memoria RAM (Tipo): {self.memoria_ram}")
    print("Cámara del teléfono: {self.camara}")
    print("Tipo del area de carga: {self.tipo_area_carga}")
    print("Marca del teléfono: {self.marca}")
    print("Almacenamiento: {self.almacenamiento}")
    print("Batería: {self.bateria}")
    print("Sistema operativo: {self.sistema_operativo}")

